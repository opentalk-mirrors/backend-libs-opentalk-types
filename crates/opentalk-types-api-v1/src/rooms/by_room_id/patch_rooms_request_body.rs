use opentalk_types_common::rooms::{GuestAccess, RoomName, RoomPassword};

/// API request parameters to patch a room
#[derive(Clone, Debug, PartialEq, Eq)]
#[cfg_attr(feature = "serde", derive(serde::Serialize, serde::Deserialize,))]
#[cfg_attr(feature = "utoipa", derive(utoipa::ToSchema))]
pub struct PatchRoomsRequestBody {
    /// A custom name that can be used as part of the URL alias to access the room instead of the [`RoomId`](opentalk_types_common::rooms::RoomId).
    ///
    /// The name is only one part of the alias. The full alias additionally contains a code that is generated by the
    /// controller. Whether such a code is generated depends on the controller configuration.
    #[cfg_attr(
        feature = "serde",
        serde(
            default,
            skip_serializing_if = "Option::is_none",
            with = "::serde_with::rust::double_option",
        )
    )]
    pub name: Option<Option<RoomName>>,

    /// The password for the room
    #[cfg_attr(
        feature = "serde",
        serde(
            default,
            skip_serializing_if = "Option::is_none",
            with = "::serde_with::rust::double_option",
        )
    )]
    pub password: Option<Option<RoomPassword>>,

    /// If waiting room is enabled
    #[cfg_attr(
        feature = "serde",
        serde(default, skip_serializing_if = "Option::is_none")
    )]
    pub waiting_room: Option<bool>,

    /// Guest access mode
    #[cfg_attr(
        feature = "serde",
        serde(default, skip_serializing_if = "Option::is_none")
    )]
    #[cfg_attr(feature = "utoipa", schema(nullable = false))]
    pub guest_access: Option<GuestAccess>,

    /// If e2e encryption is enabled
    #[cfg_attr(
        feature = "serde",
        serde(default, skip_serializing_if = "Option::is_none")
    )]
    pub e2e_encryption: Option<bool>,
}

#[cfg(all(test, feature = "serde"))]
mod serde_tests {
    use opentalk_types_common::utils::ExampleData as _;
    use pretty_assertions::assert_eq;
    use serde_json::json;

    use super::*;

    #[test]
    fn empty() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
        let body = PatchRoomsRequestBody {
            name: None,
            password: None,
            waiting_room: None,
            e2e_encryption: None,
            guest_access: None,
        };
        let json = json!({});

        let serialized = serde_json::to_value(&body)?;
        assert_eq!(serialized, json);

        let deserialized: PatchRoomsRequestBody = serde_json::from_value(json)?;
        assert_eq!(deserialized, body);

        Ok(())
    }

    #[test]
    fn full() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
        let body = PatchRoomsRequestBody {
            name: Some(Some(RoomName::example_data())),
            password: Some(Some("hello".parse()?)),
            waiting_room: Some(false),
            e2e_encryption: Some(true),
            guest_access: Some(GuestAccess::WaitingRoom),
        };
        let json = json!({
            "name": RoomName::example_data(),
            "password": "hello",
            "waiting_room": false,
            "e2e_encryption": true,
            "guest_access": "waiting_room"
        });

        let serialized = serde_json::to_value(&body)?;
        assert_eq!(serialized, json);

        let deserialized: PatchRoomsRequestBody = serde_json::from_value(json)?;
        assert_eq!(deserialized, body);

        Ok(())
    }

    #[test]
    fn reset_password() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
        let body = PatchRoomsRequestBody {
            name: None,
            password: Some(None),
            waiting_room: None,
            e2e_encryption: None,
            guest_access: None,
        };
        let json = json!({
            "password": null
        });

        let serialized = serde_json::to_value(&body)?;
        assert_eq!(serialized, json);

        let deserialized: PatchRoomsRequestBody = serde_json::from_value(json)?;
        assert_eq!(deserialized, body);

        Ok(())
    }
}
